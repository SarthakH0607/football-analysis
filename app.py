# -----------------------------------------------------------------------------
# 3. DATA LOADING
# -----------------------------------------------------------------------------
@st.cache_data
def load_data() -> pd.DataFrame:
    """Read football_players.csv and return a typed DataFrame.

    The file is generated by generate_dataset() (Sub-Task 1) and must exist
    before the app is started.  The result is cached so the CSV is only read
    once per session.
    """
    if not os.path.exists("football_players.csv"):
        st.error(
            "⚠️ Data file **football_players.csv** not found.  "
            "Please run the dataset generator before launching the app."
        )
        st.stop()

    df = pd.read_csv("football_players.csv")
    return df


# -----------------------------------------------------------------------------
# 4. DATA FILTERING
# -----------------------------------------------------------------------------
def filter_data(
    df: pd.DataFrame,
    seasons: list,
    teams: list,
    positions: list,
    players: list,
) -> pd.DataFrame:
    """Return a filtered copy of *df* based on sidebar selections.

    Each filter is applied only when the user has made a non-empty selection,
    so leaving a widget at its default (all options) passes everything through.
    """
    filtered = df.copy()

    if seasons:
        filtered = filtered[filtered["season"].isin(seasons)]
    if teams:
        filtered = filtered[filtered["team"].isin(teams)]
    if positions:
        filtered = filtered[filtered["position"].isin(positions)]
    if players:
        filtered = filtered[filtered["player_name"].isin(players)]

    return filtered


