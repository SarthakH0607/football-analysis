def render_overview(df: pd.DataFrame) -> None:
    """Overview page — KPI cards and top-performers charts."""
    # ── Section header ────────────────────────────────────────────────────
    st.markdown(
        "<h1 style='color:#00ff85;margin-bottom:0.25rem;'>📊 Overview</h1>",
        unsafe_allow_html=True,
    )

    # ── Synthetic data disclaimer banner ─────────────────────────────────
    st.markdown(
        """
        <div style="
            background-color:#3d2e00;
            border-left:4px solid #f0a500;
            border-radius:6px;
            padding:0.6rem 1rem;
            color:#f5c842;
            font-size:0.88rem;
            margin-bottom:1.25rem;
        ">
            ⚠️ This dashboard uses <strong>synthetic (fictional) data</strong>
            for demonstration purposes only. These statistics do not represent
            real football players or results.
        </div>
        """,
        unsafe_allow_html=True,
    )

    # ── KPI calculations ──────────────────────────────────────────────────
    total_players  = df["player_id"].nunique()
    total_goals    = int(df["goals"].sum())
    total_assists  = int(df["assists"].sum())
    total_minutes  = int(df["minutes_played"].sum())
    avg_rating     = round(df["rating"].mean(), 2)

    # ── KPI cards — 5 columns ────────────────────────────────────────────
    col1, col2, col3, col4, col5 = st.columns(5)

    with col1:
        st.markdown("<div class='kpi-card'>", unsafe_allow_html=True)
        st.metric("Total Players", total_players)
        st.markdown("</div>", unsafe_allow_html=True)

    with col2:
        st.markdown("<div class='kpi-card'>", unsafe_allow_html=True)
        st.metric("Total Goals", total_goals)
        st.markdown("</div>", unsafe_allow_html=True)

    with col3:
        st.markdown("<div class='kpi-card'>", unsafe_allow_html=True)
        st.metric("Total Assists", total_assists)
        st.markdown("</div>", unsafe_allow_html=True)

    with col4:
        st.markdown("<div class='kpi-card'>", unsafe_allow_html=True)
        st.metric("Total Minutes", f"{total_minutes:,}")
        st.markdown("</div>", unsafe_allow_html=True)

    with col5:
        st.markdown("<div class='kpi-card'>", unsafe_allow_html=True)
        st.metric("Avg Rating", avg_rating)
        st.markdown("</div>", unsafe_allow_html=True)

    st.markdown("<br>", unsafe_allow_html=True)

    # ── Chart data prep ───────────────────────────────────────────────────
    # Top 10 by goals — sum across seasons, sort descending
    top_goals = (
        df.groupby("player_name", as_index=False)["goals"]
        .sum()
        .sort_values("goals", ascending=False)
        .head(10)
    )

    # Top 10 by rating — mean across seasons, sort descending
    top_rating = (
        df.groupby("player_name", as_index=False)["rating"]
        .mean()
        .sort_values("rating", ascending=False)
        .head(10)
        .round({"rating": 2})
    )

    # Shared chart style helper
    _layout = dict(
        plot_bgcolor="#0d1117",
        paper_bgcolor="#0d1117",
        font=dict(color="#e6edf3"),
        xaxis=dict(color="#8b949e", gridcolor="#21262d"),
        yaxis=dict(color="#8b949e", gridcolor="#21262d"),
        margin=dict(l=10, r=10, t=40, b=10),
    )

    # ── Top 10 by Goals chart ─────────────────────────────────────────────
    fig_goals = px.bar(
        top_goals.sort_values("goals", ascending=True),
        x="goals",
        y="player_name",
        orientation="h",
        title="🏆 Top 10 Players by Goals",
        color_discrete_sequence=["#00ff85"],
    )
    fig_goals.update_layout(**_layout)
    fig_goals.update_xaxes(title_text="Goals")
    fig_goals.update_yaxes(title_text="")

    # ── Top 10 by Rating chart ────────────────────────────────────────────
    fig_rating = px.bar(
        top_rating.sort_values("rating", ascending=True),
        x="rating",
        y="player_name",
        orientation="h",
        title="⭐ Top 10 Players by Average Rating",
        color_discrete_sequence=["#00ff85"],
    )
    fig_rating.update_layout(**_layout)
    fig_rating.update_xaxes(title_text="Avg Rating", range=[0, 10])
    fig_rating.update_yaxes(title_text="")

    # ── Side-by-side charts ───────────────────────────────────────────────
    chart_col1, chart_col2 = st.columns(2)

    with chart_col1:
        st.plotly_chart(fig_goals, use_container_width=True)

    with chart_col2:
        st.plotly_chart(fig_rating, use_container_width=True)


def render_player_analysis(df: pd.DataFrame) -> None:
    """Player Analysis page — scatter plots, comparison table, stats table."""
    st.markdown("<h1 style='color:#00ff85;'>👤 Player Analysis</h1>", unsafe_allow_html=True)

    # ── Player Comparison ────────────────────────────────────────────────────
    st.subheader("⚖️ Player Comparison")
    player_names = df["player_name"].unique().tolist()
    col1, col2 = st.columns(2)
    with col1:
        player1 = st.selectbox("Select Player 1", player_names, index=0)
    with col2:
        player2 = st.selectbox(
            "Select Player 2",
            player_names,
            index=min(1, len(player_names) - 1),
        )

    comparison_stats = [
        "goals", "assists", "shots_on_target", "key_passes", "pass_accuracy",
        "tackles", "yellow_cards", "red_cards", "rating", "matches_played", "minutes_played",
    ]
    p1_row = df[df["player_name"] == player1].iloc[0]
    p2_row = df[df["player_name"] == player2].iloc[0]
    comparison_df = pd.DataFrame(
        {player1: [p1_row[s] for s in comparison_stats],
         player2: [p2_row[s] for s in comparison_stats]},
        index=comparison_stats,
    )
    st.dataframe(comparison_df, use_container_width=True)

    # ── Scatter Plots ─────────────────────────────────────────────────────────
    dark_layout = dict(
        plot_bgcolor="#0d1117",
        paper_bgcolor="#0d1117",
        font=dict(color="#e6edf3"),
        xaxis=dict(gridcolor="#21262d", zerolinecolor="#21262d"),
        yaxis=dict(gridcolor="#21262d", zerolinecolor="#21262d"),
        legend=dict(bgcolor="#0d1117", bordercolor="#21262d"),
    )

    fig_goals_assists = px.scatter(
        df,
        x="assists",
        y="goals",
        color="position",
        hover_data=["player_name", "team", "rating", "season"],
        title="🎯 Goals vs Assists",
        color_discrete_sequence=px.colors.qualitative.Bold,
    )
    fig_goals_assists.update_layout(**dark_layout)

    fig_shots_goals = px.scatter(
        df,
        x="shots_on_target",
        y="goals",
        trendline="ols",
        color="position",
        hover_data=["player_name", "team"],
        title="🔫 Shots on Target vs Goals",
        color_discrete_sequence=px.colors.qualitative.Bold,
    )
    fig_shots_goals.update_layout(**dark_layout)

    scatter_col1, scatter_col2 = st.columns(2)
    with scatter_col1:
        st.plotly_chart(fig_goals_assists, use_container_width=True)
    with scatter_col2:
        st.plotly_chart(fig_shots_goals, use_container_width=True)

    # ── Searchable Player Stats Table ─────────────────────────────────────────
    st.subheader("📋 Player Statistics")
    search_term = st.text_input("🔍 Search player name...")
    filtered_table = df[df["player_name"].str.contains(search_term, case=False, na=False)]
    st.dataframe(filtered_table, use_container_width=True)
    st.caption(f"Showing {len(filtered_table)} records")

    # ── CSV Download ──────────────────────────────────────────────────────────
    st.download_button(
        label="⬇️ Download Filtered Data as CSV",
        data=filtered_table.to_csv(index=False).encode("utf-8"),
        file_name="football_players_filtered.csv",
        mime="text/csv",
    )


def render_team_analysis(df: pd.DataFrame) -> None:
    """Team Analysis page — grouped bar, squad depth, radar chart."""
    st.markdown("<h1 style='color:#00ff85;'>🏟️ Team Analysis</h1>", unsafe_allow_html=True)

    # ------------------------------------------------------------------
    # Team aggregation
    # ------------------------------------------------------------------
    team_agg = (
        df.groupby("team")
        .agg(
            total_goals=("goals", "sum"),
            total_assists=("assists", "sum"),
            total_minutes=("minutes_played", "sum"),
            avg_rating=("rating", "mean"),
            player_count=("player_id", "nunique"),
        )
        .reset_index()
    )
    team_agg["avg_rating"] = team_agg["avg_rating"].round(2)

    # ------------------------------------------------------------------
    # Grouped bar chart — Goals & Assists per Team
    # ------------------------------------------------------------------
    melted_df = team_agg[["team", "total_goals", "total_assists"]].melt(
        id_vars="team",
        value_vars=["total_goals", "total_assists"],
        var_name="Stat",
        value_name="Value",
    )
    melted_df["Stat"] = melted_df["Stat"].map(
        {"total_goals": "Goals", "total_assists": "Assists"}
    )

    fig_goals_assists = px.bar(
        melted_df,
        x="team",
        y="Value",
        color="Stat",
        barmode="group",
        title="⚽ Goals & Assists by Team",
        color_discrete_map={"Goals": "#00ff85", "Assists": "#7c5cd8"},
    )
    fig_goals_assists.update_layout(
        plot_bgcolor="#0d1117",
        paper_bgcolor="#0d1117",
        font_color="#e6edf3",
        xaxis=dict(gridcolor="#30363d"),
        yaxis=dict(gridcolor="#30363d"),
    )

    # ------------------------------------------------------------------
    # Squad depth bar chart — Players per Team
    # ------------------------------------------------------------------
    fig_squad = px.bar(
        team_agg,
        x="team",
        y="player_count",
        title="👥 Squad Depth by Team",
        color_discrete_sequence=["#00ff85"],
    )
    fig_squad.update_layout(
        plot_bgcolor="#0d1117",
        paper_bgcolor="#0d1117",
        font_color="#e6edf3",
        xaxis=dict(gridcolor="#30363d"),
        yaxis=dict(gridcolor="#30363d"),
    )

    # Place the two bar charts side by side
    col1, col2 = st.columns(2)
    with col1:
        st.plotly_chart(fig_goals_assists, use_container_width=True)
    with col2:
        st.plotly_chart(fig_squad, use_container_width=True)

    # ------------------------------------------------------------------
    # Radar chart — Multi-Team Comparison
    # ------------------------------------------------------------------
    st.subheader("🕸️ Team Radar Comparison")

    all_teams = team_agg["team"].tolist()
    default_teams = all_teams[:3]

    selected_teams = st.multiselect(
        "Select up to 5 teams",
        options=all_teams,
        default=default_teams,
        max_selections=5,
    )

    if selected_teams:
        radar_cols = ["total_goals", "total_assists", "avg_rating", "player_count"]
        radar_data = team_agg[team_agg["team"].isin(selected_teams)].copy()

        # Normalise each stat 0–1 across all teams (not just selected)
        norm_data = radar_data[radar_cols].copy()
        for col in radar_cols:
            col_min = team_agg[col].min()
            col_max = team_agg[col].max()
            if col_max == col_min:
                norm_data[col] = 0.5
            else:
                norm_data[col] = (norm_data[col] - col_min) / (col_max - col_min)

        radar_labels = ["Total Goals", "Total Assists", "Avg Rating", "Player Count"]

        fig_radar = go.Figure()
        for i, team_name in enumerate(radar_data["team"].tolist()):
            values = norm_data.iloc[i][radar_cols].tolist()
            # Close the polygon
            values_closed = values + [values[0]]
            labels_closed = radar_labels + [radar_labels[0]]
            fig_radar.add_trace(
                go.Scatterpolar(
                    r=values_closed,
                    theta=labels_closed,
                    fill="toself",
                    name=team_name,
                )
            )

        fig_radar.update_layout(
            polar=dict(
                bgcolor="#0d1117",
                radialaxis=dict(
                    visible=True,
                    range=[0, 1],
                    gridcolor="#30363d",
                    linecolor="#30363d",
                    tickfont=dict(color="#e6edf3"),
                ),
                angularaxis=dict(
                    gridcolor="#30363d",
                    linecolor="#30363d",
                    tickfont=dict(color="#e6edf3"),
                ),
            ),
            paper_bgcolor="#0d1117",
            font_color="#e6edf3",
            showlegend=True,
        )
        st.plotly_chart(fig_radar, use_container_width=True)

    # ------------------------------------------------------------------
    # Team Summary Table
    # ------------------------------------------------------------------
    st.subheader("📊 Team Summary")
    st.dataframe(team_agg, use_container_width=True)


def render_position_analysis(df: pd.DataFrame) -> None:
    """Position Analysis page — box plot, average stats, scatter, table."""
    # ── Section header ────────────────────────────────────────────────────
    st.markdown(
        "<h1 style='color:#00ff85;margin-bottom:0.25rem;'>📍 Position Analysis</h1>",
        unsafe_allow_html=True,
    )

    # Shared dark layout config
    _dark = dict(
        plot_bgcolor="#0d1117",
        paper_bgcolor="#0d1117",
        font=dict(color="#e6edf3"),
        xaxis=dict(gridcolor="#21262d", zerolinecolor="#21262d"),
        yaxis=dict(gridcolor="#21262d", zerolinecolor="#21262d"),
        legend=dict(bgcolor="#0d1117", bordercolor="#21262d"),
    )

    _pos_order = ["GK", "DEF", "MID", "FWD"]
    _pos_colors = {
        "GK":  "#3b82d4",
        "DEF": "#00ff85",
        "MID": "#7c5cd8",
        "FWD": "#ff6b6b",
    }

    # ── Rating Distribution Box Plot ──────────────────────────────────────
    fig_box = px.box(
        df,
        x="position",
        y="rating",
        color="position",
        title="⭐ Rating Distribution by Position",
        category_orders={"position": _pos_order},
        color_discrete_map=_pos_colors,
    )
    fig_box.update_layout(**_dark)

    # ── Average Stats Bar Chart ───────────────────────────────────────────
    pos_stats = (
        df.groupby("position")[["goals", "assists", "tackles"]]
        .mean()
        .round(2)
        .reset_index()
    )
    melted = pd.melt(
        pos_stats,
        id_vars="position",
        value_vars=["goals", "assists", "tackles"],
        var_name="Stat",
        value_name="Value",
    )
    fig_bar = px.bar(
        melted,
        x="position",
        y="Value",
        color="Stat",
        barmode="group",
        title="📈 Average Goals, Assists & Tackles by Position",
        category_orders={"position": _pos_order},
        color_discrete_map={
            "goals":   "#00ff85",
            "assists": "#7c5cd8",
            "tackles": "#3b82d4",
        },
    )
    fig_bar.update_layout(**_dark)

    # ── Side-by-side charts ───────────────────────────────────────────────
    col1, col2 = st.columns(2)
    with col1:
        st.plotly_chart(fig_box, use_container_width=True)
    with col2:
        st.plotly_chart(fig_bar, use_container_width=True)

    # ── Pass Accuracy vs Key Passes Scatter ───────────────────────────────
    fig_scatter = px.scatter(
        df,
        x="key_passes",
        y="pass_accuracy",
        color="position",
        hover_data=["player_name", "team", "goals"],
        title="🎯 Pass Accuracy vs Key Passes",
        category_orders={"position": _pos_order},
        color_discrete_map=_pos_colors,
    )
    fig_scatter.update_layout(**_dark)
    st.plotly_chart(fig_scatter, use_container_width=True)

    # ── Position Averages Table ───────────────────────────────────────────
    st.subheader("📊 Position Averages")
    pos_avg = df.groupby("position").mean(numeric_only=True).round(2)
    if "player_id" in pos_avg.columns:
        pos_avg = pos_avg.drop(columns=["player_id"])
    st.dataframe(pos_avg, use_container_width=True)


# -----------------------------------------------------------------------------
# 6. MAIN — sidebar, filters, and page dispatch
# -----------------------------------------------------------------------------
def main() -> None:
    # ── Load full dataset ──────────────────────────────────────────────────
    df = load_data()

    # ── Sidebar ───────────────────────────────────────────────────────────
    st.sidebar.markdown("# ⚽ Football Analytics")
    st.sidebar.markdown("---")

    # Navigation
    page = st.sidebar.radio(
        "Navigate to",
        options=[
            "📊 Overview",
            "👤 Player Analysis",
            "🏟️ Team Analysis",
            "📍 Position Analysis",
        ],
    )

    st.sidebar.markdown("---")
    st.sidebar.markdown("### Filters")

    # Season filter
    all_seasons = sorted(df["season"].unique().tolist())
    seasons = st.sidebar.multiselect(
        "Season",
        options=all_seasons,
        default=[],
        placeholder="All seasons",
    )

    # Team filter
    all_teams = sorted(df["team"].unique().tolist())
    teams = st.sidebar.multiselect(
        "Team",
        options=all_teams,
        default=[],
        placeholder="All teams",
    )

    # Position filter
    all_positions = sorted(df["position"].unique().tolist())
    positions = st.sidebar.multiselect(
        "Position",
        options=all_positions,
        default=[],
        placeholder="All positions",
    )

    # Player filter (optional extra filter)
    all_players = sorted(df["player_name"].unique().tolist())
    players = st.sidebar.multiselect(
        "Player",
        options=all_players,
        default=[],
        placeholder="All players",
    )

    st.sidebar.markdown("---")
    st.sidebar.markdown(
        "<small>⚠️ <b>Synthetic Data</b> — figures do not represent "
        "real players or competitions.</small>",
        unsafe_allow_html=True,
    )

    # ── Apply filters ─────────────────────────────────────────────────────
    filtered_df = filter_data(df, seasons, teams, positions, players)

    if filtered_df.empty:
        st.warning("⚠️ No data matches the current filters. Please adjust your selection.")
        st.stop()

    # ── Dispatch to the selected page ─────────────────────────────────────
    if page == "📊 Overview":
        render_overview(filtered_df)
    elif page == "👤 Player Analysis":
        render_player_analysis(filtered_df)
    elif page == "🏟️ Team Analysis":
        render_team_analysis(filtered_df)
    elif page == "📍 Position Analysis":
        render_position_analysis(filtered_df)


# Entry point
# Streamlit executes module-level code directly — call main() unconditionally.
main()
